export const getMonthName = (monthDate: Date): string => {
  const monthNames = [
    "January",
    "February",
    "March",
    "April",
    "May",
    "June",
    "July",
    "August",
    "September",
    "October",
    "November",
    "December",
  ];
  return `${monthNames[monthDate.getMonth()]} ${monthDate.getFullYear()}`;
};
